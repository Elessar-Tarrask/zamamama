import { describe, expect, it } from "vitest";
import { RULE_SECTIONS, buildSystemPrompt } from "../src/llm/prompt";
import { DEFAULT_SETTINGS } from "../src/seed/seedData";
import type { Conversation } from "../src/types";

const conv: Conversation = { mode: "bot", lead: {}, lastInboundAtMs: 0, createdAtMs: 0 };
const prompt = buildSystemPrompt(DEFAULT_SETTINGS, [], conv, Date.UTC(2026, 7, 10, 4));
const allRules = RULE_SECTIONS.flatMap((s) => s.rules);

describe("свод правил бота", () => {
  it("содержит не меньше 75 правил (базовые + 50 практик + 10 антиспам)", () => {
    expect(allRules.length).toBeGreaterThanOrEqual(75);
  });

  it("покрывает все 7 тематических секций", () => {
    const titles = RULE_SECTIONS.map((s) => s.title);
    expect(titles).toEqual([
      "ТОН И СТИЛЬ",
      "ЯЗЫК И ФОРМАТИРОВАНИЕ WHATSAPP",
      "ВЕДЕНИЕ ДИАЛОГА",
      "ПРОДАЖА И ЛИДЫ — МЯГКО",
      "ЗАПИСЬ НА ЭКСКУРСИЮ",
      "ГРАНИЦЫ И БЕЗОПАСНОСТЬ",
      "АНТИСПАМ И ГРАНИЦЫ ТЕМЫ",
      "ДАННЫЕ И ЧЕСТНОСТЬ",
    ]);
    for (const s of RULE_SECTIONS) {
      expect(s.rules.length).toBeGreaterThan(0);
      expect(prompt).toContain(s.title); // каждая секция реально попадает в промпт
    }
  });

  it("все правила пронумерованы в промпте сквозной нумерацией", () => {
    expect(prompt).toContain("1. ");
    expect(prompt).toContain(`${allRules.length}. `);
  });

  const mustHave: Array<[string, string]> = [
    ["один вопрос за раз", "не больше ОДНОГО вопроса"],
    ["один эмодзи максимум", "Максимум один эмодзи"],
    ["без капса", "КАПСОМ"],
    ["без канцелярита", "канцелярита"],
    ["позитивные формулировки", "не «мы не работаем в субботу»"],
    ["язык последнего сообщения", "языке его последнего сообщения"],
    ["местное время", "никаких UTC"],
    ["ответить на все вопросы", "ответь на ВСЕ по порядку"],
    ["повторное здравствуйте", "не перезапускает приветственный скрипт"],
    ["принимать поправки", "сразу прими правку"],
    ["короткое закрытие на спасибо", "Без нового питча"],
    ["не указывать на опечатки", "не указывай клиенту на его ошибки"],
    ["не давить после отказа", "Повторно не уговаривай"],
    ["дорого — не спорить", "Скидки сам НИКОГДА"],
    ["не критиковать конкурентов", "не сравнивай себя с другими садиками"],
    ["аллергии к админу", "Особые потребности, аллергии"],
    ["возраст вне 2–6", "младше 2 или старше 6"],
    ["подтверждение брони", "повтори всё подтверждением"],
    ["перенос через админа", "Отмена или перенос записи"],
    ["выходные → будни", "мягко предложи пятницу или понедельник"],
    ["без медицинских советов", "медицинских, юридических"],
    ["жалоба — сочувствие и handoff", "не защищайся и не спорь"],
    ["срочное — handoff", "безопасности ребёнка"],
    ["не раскрывать других клиентов", "не обсуждай других клиентов"],
    ["не раскрывать устройство", "как ты устроена"],
    ["самозванцы", "представляется сотрудником"],
    ["нет файлов — не обещать", "обещай отправить файлы"],
    ["не озвучивать внутренние действия", "внутренних действиях"],
    ["имя из WhatsApp не настоящее", "не настоящее имя клиента"],
    ["не просить оплату в чате", "данные карт"],
    ["без выдуманных сроков", "точных сроков ответа администратора"],
    ["не писать первым чужим", "не пиши первым другим людям"],
    ["не повторять блоки", "НЕ отправляй повторно"],
    ["log_unanswered вместо выдумки", "log_unanswered_question"],
    ["эскалация оффтопа", "посторонний контент вообще не комментируй"],
    ["темы-табу", "Темы-табу"],
    ["не открывать ссылки", "Ссылки и файлы не открывай"],
    ["реклама — не вовлекаться", "Реклама и предложения услуг"],
    ["только этот чат WhatsApp", "только в этом чате WhatsApp"],
    ["не играть в проверки бота", "«Проверки бота»"],
  ];

  for (const [name, needle] of mustHave) {
    it(`правило «${name}» присутствует в промпте`, () => {
      expect(prompt).toContain(needle);
    });
  }
});
