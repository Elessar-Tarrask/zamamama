/**
 * Детерминированный разбор входящего сообщения: вытаскиваем факты, которые
 * клиент уже назвал, и кладём в профиль лида ДО вызова модели — чтобы бот
 * никогда не переспрашивал то, что ему уже сказали.
 */

const WORD_AGES: Record<string, number> = {
  один: 1, одного: 1,
  два: 2, двух: 2, две: 2,
  три: 3, трех: 3,
  четыре: 4, четырех: 4,
  пять: 5, пяти: 5,
  шесть: 6, шести: 6,
  семь: 7, семи: 7,
};

/** Возраст ребёнка из свободного текста (1–7 лет), иначе undefined. */
export function extractChildAge(text: string | undefined): number | undefined {
  if (!text) return undefined;
  const t = text.toLowerCase().replace(/ё/g, "е");

  // «2 годика», «3 года», «4 лет», «2,5 года» — дробные округляем вниз
  const digit = t.match(/(?:^|\D)(\d{1,2})(?:[.,]5)?\s*(?:годика|годик|года|год|лет)/);
  if (digit) {
    const n = parseInt(digit[1], 10);
    if (n >= 1 && n <= 7) return n;
    return undefined;
  }

  // «два годика», «три года», «пяти лет»
  const word = t.match(/(?:^|\s)(один|одного|два|двух|две|три|трех|четыре|четырех|пять|пяти|шесть|шести|семь|семи)\s*(?:годика|годик|года|год|лет)/);
  if (word) return WORD_AGES[word[1]];

  // «нам годик» = 1 год
  if (/(?:нам|ему|ей|сыну|дочке|малышу|ребенку)\s+годик/.test(t)) return 1;

  return undefined;
}
